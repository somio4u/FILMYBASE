// AI Cinematic Spectacle & Mass Entertainment Director  (agent id: ai-cinematic-spectacle-director)
// AI Movie only. Runs on Gemini 3.1 Pro in every quality mode (see modelRouting.js).
//
// It never overwrites anything. It makes PROPOSALS that wait for the user:
//   story_rec           ideas for the Story Bible -> sent to the existing Story Brain as a note
//                       (head writer + critics review it); the Bible itself is never edited here.
//   screenplay_change   a proposed enhanced version of one scene -> shown next to the original;
//                       only when the user approves it is the scene replaced, and that puts the beat
//                       back into the normal screenplay review (so the user approves the result again).
//   cinematic_direction structured directions for one scene (hero/villain moments, fight choreography,
//                       camera, AI-production shot plan, continuity, extra assets). They never touch the
//                       screenplay. Once approved they flow into the Silent Agent and the Shot Cutter.
//
// Versioning: every item remembers the exact scene text it was made from (a hash). If the scene is edited
// afterwards the item is STALE and is never sent to production (it must be made again).

import crypto from "node:crypto";
import { assertWithinBudget } from "./pipelineSettings.js";
import { estimateCost, modelFor, shotCutterRoute } from "./modelRouting.js";

export const AGENT_ID = "ai-cinematic-spectacle-director";
const sha = (text) => crypto.createHash("sha256").update(String(text)).digest("hex").slice(0, 32);
export const sceneHash = (text) => sha(String(text).replace(/\s+/g, " ").trim());
const httpError = (message, status = 400, code = null) => Object.assign(new Error(message), { status, code });

export async function ensureCinematicSchema(db) {
  const statements = [
    `ALTER TABLE ai_movie_projects ADD COLUMN IF NOT EXISTS cinematic_job JSONB`,
    `CREATE TABLE IF NOT EXISTS ai_movie_cinematic_items (
      id SERIAL PRIMARY KEY,
      project_id INTEGER NOT NULL REFERENCES ai_movie_projects(id) ON DELETE CASCADE,
      kind TEXT NOT NULL CHECK (kind IN ('story_rec','screenplay_change','cinematic_direction')),
      scene_key TEXT,
      scene_hash TEXT NOT NULL,
      mode TEXT NOT NULL DEFAULT 'mass',
      status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','applied','sent','superseded')),
      title TEXT NOT NULL DEFAULT '',
      summary TEXT NOT NULL DEFAULT '',
      original_text TEXT,
      payload JSONB NOT NULL DEFAULT '{}',
      edited BOOLEAN NOT NULL DEFAULT false,
      paired_item_id INTEGER,
      model TEXT,
      quality_mode TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      decided_at TIMESTAMPTZ,
      decided_by INTEGER
    )`,
    `CREATE INDEX IF NOT EXISTS ai_movie_cinematic_items_project_idx ON ai_movie_cinematic_items (project_id, kind, scene_key)`,
  ];
  for (const sql of statements) await db.query(sql);
}

