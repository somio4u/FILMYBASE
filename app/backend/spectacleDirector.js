export function storyRecsPrompt(bibleMarkdown, cinematicMode) {
  return {
    systemInstruction: `${PHILOSOPHY}\n\n${MODE_BRIEF[cinematicMode] ?? MODE_BRIEF.mass}`,
    contents: `Read this Story Bible and propose how to make the film more visually unforgettable WITHOUT changing the story's facts, characters or ending. You are not rewriting the Bible: your recommendations go to the Story Brain (head writer and critics), who decide what to take.\n\nSuggest: stronger visual concepts; cinematic world-building; memorable hero and villain moments; visually compelling conflict; signature action sequences; the interval; grand climax possibilities.\n\n${bibleMarkdown}`,
    responseSchema: STORY_RECS_SCHEMA,
    maxOutputTokens: 16384,
  };
}

export function scenePrompt({ cinematicMode, sceneText, sceneKey, contextText, allowRewrite, characterBriefs }) {
  const rewriteRule = allowRewrite
    ? `If — and only if — a rewrite would clearly make the scene better (replace unnecessary dialogue with action, strengthen visual storytelling, improve pacing, add a memorable moment, elevate a fight) return the COMPLETE rewritten scene in enhancedHeading + enhancedBlocks. Keep the story events, the characters' voices and everything the rest of the film depends on. If the scene is already right, leave enhancedBlocks EMPTY.`
    : `The screenplay is APPROVED and locked. Do NOT rewrite it: leave enhancedHeading empty and enhancedBlocks EMPTY. Give directions only — how to SHOOT this scene as written.`;
  return {
    systemInstruction: `${PHILOSOPHY}\n\n${MODE_BRIEF[cinematicMode] ?? MODE_BRIEF.mass}\n\n${SCREENSCREEN}`,
    contents: `${contextText ? `THE FILM SO FAR (for context only):\n${contextText}\n\n` : ""}${characterBriefs ? `CHARACTERS:\n${characterBriefs}\n\n` : ""}SCENE ${sceneKey} — analyse this scene and return structured cinematic directions.\n\n${sceneText}\n\n${rewriteRule}\n\nFill every field honestly. If the scene needs no spectacle, set spectacleLevel "none" and keep the other lists short. A fight needs the full fights entry; a scene with no fight has an empty fights list.`,
    responseSchema: DIRECTION_SCHEMA,
    maxOutputTokens: 32768,
  };
}

