// Approved, still-current directions for ONE scene (source key like "b3s2"), or null. Stale ones are never returned.
export async function approvedDirectionFor(db, projectId, sceneKey, currentText) {
  const hash = sceneHash(currentText);
  const row = (await db.query(
    `SELECT payload FROM ai_movie_cinematic_items WHERE project_id = $1 AND kind = 'cinematic_direction' AND scene_key = $2 AND status IN ('approved','sent') AND scene_hash = $3 ORDER BY id DESC LIMIT 1`,
    [projectId, sceneKey, hash]
  )).rows[0];
  return row ? row.payload : null;
}

// Silent Agent: extra assets the approved directions need (props, costumes, locations, characters).
export async function cinematicAssetNotesText(db, projectId, currentHashes) {
  const rows = (await db.query("SELECT scene_key, scene_hash, payload FROM ai_movie_cinematic_items WHERE project_id = $1 AND kind = 'cinematic_direction' AND status IN ('approved','sent') ORDER BY id", [projectId])).rows;
  const lines = [];
  for (const r of rows) {
    if (currentHashes.get(r.scene_key) !== r.scene_hash) continue; // stale — never reaches production
    for (const a of r.payload.newAssets ?? []) lines.push(`- (${a.kind}) ${a.name}: ${a.description} [needed by approved cinematic direction for scene ${r.scene_key}]`);
  }
  return lines.length ? `APPROVED CINEMATIC ADDITIONS (production assets the Cinematic Director's approved directions need — include them in the lists):\n${lines.join("\n")}` : "";
}

// Shot Cutter / Video Maker: the approved directions as plain text for a prompt.
export function directionPromptBlock(payload) {
  if (!payload) return "";
  return `APPROVED CINEMATIC DIRECTIONS FOR THIS SCENE (from the Cinematic Spectacle Director — follow them: keep the framing, camera moves, shot order and continuity; do not add story events):\n${directionToText(payload)}`;
}

// Shot Cutter: approved (and still current) cinematic directions for the scene go into its brief, and the model is
// chosen by quality mode — Pro for complex action, Flash otherwise (Maximum: Pro for all). It always goes through the money guard.
// Returns null for a scene that does not come from the AI Movie screenplay (the normal cutter then runs unchanged).
export function createShotCutterHook({ db, ask, getScenes }) {
  return async function shotCutterFor(projectId, sceneId) {
    const scene = (await db.query("SELECT source_kind, source_key FROM production_scenes WHERE id = $1 AND project_id = $2", [sceneId, projectId])).rows[0];
    if (!scene || scene.source_kind !== "beats") return null;
    const current = (await getScenes(projectId)).find((s) => s.key === scene.source_key);
    if (!current) return null;
    const direction = await approvedDirectionFor(db, projectId, scene.source_key, current.text);
    const { qualityMode } = await ask.getModes(projectId);
    const route = shotCutterRoute(qualityMode, { text: current.text, characterCount: current.characters.length, direction });
    const agent = route.tier === "pro" ? "shot-cutter-complex" : "shot-cutter";
    return {
      extraPrompt: directionPromptBlock(direction),
      model: route.label,
      textJson: async (prompt) => (await ask.ask(projectId, agent, { contents: prompt, maxOutputTokens: 16384 })).data,
    };
  };
}
