function directionTitle(d, heading) {
  const lead = d.fights?.[0]?.identity || d.massMoments?.[0]?.name || d.heroIntroduction?.slice(0, 60) || d.villainPresentation?.slice(0, 60) || d.purpose?.slice(0, 80) || "Cinematic directions";
  return `${heading ? `${heading} — ` : ""}${lead}`.slice(0, 200);
}

export function directionToText(payload) {
  const d = payload ?? {};
  const lines = [`SPECTACLE LEVEL: ${d.spectacleLevel ?? "none"}${d.purpose ? ` — ${d.purpose}` : ""}`];
  if (d.heroIntroduction) lines.push(`HERO INTRODUCTION: ${d.heroIntroduction}`);
  if (d.villainPresentation) lines.push(`VILLAIN PRESENTATION: ${d.villainPresentation}`);
  for (const m of d.massMoments ?? []) lines.push(`MASS MOMENT "${m.name}": ${m.visual} (payoff: ${m.payoff})`);
  for (const f of d.fights ?? []) {
    lines.push(`FIGHT — ${f.identity}: motivation: ${f.motivation}. Styles: ${f.fightingStyles}. Geography: ${f.spatialGeography}.`);
    if (f.environmentInteraction?.length) lines.push(`  Environment: ${f.environmentInteraction.join("; ")}`);
    (f.progression ?? []).forEach((p) => lines.push(`  ${p.phase}: ${p.action} [camera: ${p.camera}]`));
    if (f.reversals?.length) lines.push(`  Reversals: ${f.reversals.join("; ")}`);
    if (f.signatureBeats?.length) lines.push(`  Signature beats: ${f.signatureBeats.join("; ")}`);
    lines.push(`  Payoff: ${f.payoff}`);
  }
  for (const x of d.dialogueToAction ?? []) lines.push(`SHOW INSTEAD OF TELL: "${x.original}" -> ${x.replacement}`);
  if (d.camera) lines.push(`CAMERA: opens on ${d.camera.openingShot}. Moves: ${(d.camera.signatureMoves ?? []).join("; ")}. ${d.camera.lensNotes ?? ""}`);
  const ai = d.aiProduction ?? {};
  (ai.shotPlan ?? []).forEach((s) => lines.push(`SHOT ${s.n}: ${s.description} (${s.framing}, ${s.cameraMove}, ${s.durationSec}s)${s.continuityNotes ? ` — keep: ${s.continuityNotes}` : ""}`));
  if (ai.continuity) lines.push(`CONTINUITY: characters ${ai.continuity.characters}; costumes ${ai.continuity.costumes}; weapons/props ${ai.continuity.weapons}; locations ${ai.continuity.locations}; camera direction ${ai.continuity.cameraDirection}; geography ${ai.continuity.geography}`);
  for (const a of ai.alternatives ?? []) lines.push(`IF HARD TO GENERATE (${a.situation}): ${a.approach}`);
  return lines.join("\n");
}

const clean = (v) => String(v ?? "").trim();

export function enhancedSceneText(payload) {
  const blocks = payload?.enhancedBlocks ?? [];
  if (blocks.length === 0) return "";
  return `${clean(payload.enhancedHeading)}\n${blocks.map((b) => (b.type === "dialogue" ? `${clean(b.character)}${b.parenthetical ? ` (${clean(b.parenthetical)})` : ""}\n${clean(b.text)}` : clean(b.text))).join("\n\n")}`.trim();
}

